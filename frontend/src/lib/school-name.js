/**
 * แปลงชื่อสถานศึกษาให้อ่านเป็นทางการ: เอารหัสโรงเรียนออก ใช้คำว่า "โรงเรียน" แทน
 *
 * ตัวอย่าง
 *   "54020001 บ้านน้ำริน (คุรุราษฎร์รังสรรค์)" → "โรงเรียนบ้านน้ำริน (คุรุราษฎร์รังสรรค์)"
 *   "54020001 โรงเรียนบ้านน้ำริน"            → "โรงเรียนบ้านน้ำริน"
 *   "54020001"                                → "โรงเรียน"
 *   "โรงเรียนบ้านน้ำริน"                       → "โรงเรียนบ้านน้ำริน" (ไม่แตะ)
 *
 * ใช้กับ "เขียนที่" ของแบบฟอร์มไปราชการฝั่งสถานศึกษา
 * (ทั้งหน้าต่างยื่นคำขอและเอกสารรายละเอียด)
 */
export function schoolDisplayName(raw) {
  const s = String(raw || '').trim();
  if (!s) return 'โรงเรียน';
  const m = s.match(/^(\d{7,8})\s*(.*)$/);
  if (!m) return s;
  const rest = String(m[2] || '').trim();
  if (!rest) return 'โรงเรียน';
  if (/^โรงเรียน/.test(rest)) return rest;
  return 'โรงเรียน' + rest;
}
