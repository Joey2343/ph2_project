/**
 * ตัวเลือก "กรุณาเลือกตำแหน่งที่จะอนุมัติ/อนุญาต"
 *
 * ผู้ใช้สั่ง 12 พ.ย. 2569
 *   "ให้มีตัวเลือก รองผู้อำนวยการสำนักงานเขตพื้นที่การศึกษาประถมศึกษาแพร่ เขต 2,
 *    รองผู้อำนวยการ… รักษาราชการแทน ผอ.สพป.แพร่ เขต 2,
 *    รองผู้อำนวยการ… ปฏิบัติราชการแทน ผอ.สพป.แพร่ เขต 2"
 *
 * กติกา
 *   · รอง ผอ.สพป.  → 3 ตัวเลือก (ตำแหน่งจริง / รักษาราชการแทน / ปฏิบัติราชการแทน)
 *   · ผอ.สพป.      → ตำแหน่งจริง + ปฏิบัติหน้าที่ราชการแทนเลขาธิการ กพฐ.
 *   · อื่น ๆ        → ตำแหน่งจริง + 3 ตัวเลือกของรอง ผอ.สพป. (เผื่อใช้ลงนามแทนกัน)
 *
 * ⚠️ ต้องใช้ตัวช่วยตัวเดียวทั้งระบบ (ลา · ไปราชการ) ไม่งั้นตัวเลือกจะไม่ตรงกัน
 */

export const DIRECTOR = 'ผู้อำนวยการสำนักงานเขตพื้นที่การศึกษาประถมศึกษาแพร่ เขต 2';
export const DEPUTY = 'รองผู้อำนวยการสำนักงานเขตพื้นที่การศึกษาประถมศึกษาแพร่ เขต 2';
/** 3 ตัวเลือกของรอง ผอ.สพป. (ผู้ใช้สั่ง 12 พ.ย. 2569) */
export const DEPUTY_OPTIONS = [
  DEPUTY,
  `${DEPUTY} รักษาราชการแทน ผอ.สพป.แพร่ เขต 2`,
  `${DEPUTY} ปฏิบัติราชการแทน ผอ.สพป.แพร่ เขต 2`,
];

/**
 * @param {string} position ตำแหน่งจริงของผู้ใช้
 * @returns {string[]} ตัวเลือกสำหรับ dropdown (ไม่ซ้ำ)
 */
export function approvePositionOptions(position) {
  const p = String(position || '').trim();
  if (p.includes(`รอง${DIRECTOR}`) || p === DEPUTY || p.startsWith(DEPUTY)) {
    return [...DEPUTY_OPTIONS];
  }
  if (p.includes(DIRECTOR) && !p.includes('รอง')) {
    return [DIRECTOR, `${DIRECTOR} ปฏิบัติหน้าที่ราชการแทนเลขาธิการ กพฐ.`];
  }
  const own = p || 'ไม่ระบุตำแหน่ง';
  const out = [own];
  for (const opt of DEPUTY_OPTIONS) {
    if (!out.includes(opt)) out.push(opt);
  }
  return out;
}
